#!/usr/bin/env node
/**
 * Writes client/.env.local with defaults; preserves existing VAPID / WEBHOOK_SECRET when set.
 * Run: npm run env:local
 */

const fs = require('fs')
const path = require('path')
const crypto = require('crypto')

const webpush = require('web-push')

const ROOT = path.join(__dirname, '..')
const ENV_PATH = path.join(ROOT, '.env.local')

/** Empty = same-origin `/api` (Next rewrites to Fastify). */
const DEFAULT_API = ''
const DEFAULT_DEV_ID = '00000000-0000-4000-8000-000000000001'
const DEFAULT_SITE_URL = 'http://localhost:3000'
const DEFAULT_VAPID_SUBJECT = 'mailto:you@example.com'

function parseEnvFile(p) {
  if (!fs.existsSync(p)) return {}
  const raw = fs.readFileSync(p, 'utf8')
  const out = {}
  for (const line of raw.split('\n')) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const i = t.indexOf('=')
    if (i === -1) continue
    const key = t.slice(0, i).trim()
    out[key] = t.slice(i + 1).trim()
  }
  return out
}

function main() {
  const prev = parseEnvFile(ENV_PATH)

  let pub = prev.NEXT_PUBLIC_VAPID_PUBLIC_KEY
  let priv = prev.VAPID_PRIVATE_KEY
  if (!pub || !priv) {
    const keys = webpush.generateVAPIDKeys()
    pub = pub || keys.publicKey
    priv = priv || keys.privateKey
  }

  const webhook =
    prev.WEBHOOK_SECRET || crypto.randomBytes(32).toString('hex')

  const apiUrl =
    prev.NEXT_PUBLIC_API_URL !== undefined
      ? prev.NEXT_PUBLIC_API_URL
      : process.env.NEXT_PUBLIC_API_URL !== undefined
        ? process.env.NEXT_PUBLIC_API_URL
        : DEFAULT_API
  const devId =
    prev.NEXT_PUBLIC_DEV_USER_ID ||
    process.env.NEXT_PUBLIC_DEV_USER_ID ||
    DEFAULT_DEV_ID
  const devEmail =
    prev.NEXT_PUBLIC_DEV_EMAIL ||
    process.env.NEXT_PUBLIC_DEV_EMAIL ||
    'dev@local.test'
  const siteUrl = prev.SITE_URL || process.env.SITE_URL || DEFAULT_SITE_URL
  const vapidSubject =
    prev.VAPID_SUBJECT || process.env.VAPID_SUBJECT || DEFAULT_VAPID_SUBJECT

  const lines = [
    '# Generated by scripts/write-env-local.js',
    '',
    `NEXT_PUBLIC_API_URL=${apiUrl}`,
    `NEXT_PUBLIC_DEV_USER_ID=${devId}`,
    `NEXT_PUBLIC_DEV_EMAIL=${devEmail}`,
    '',
    `NEXT_PUBLIC_VAPID_PUBLIC_KEY=${pub}`,
    `VAPID_PRIVATE_KEY=${priv}`,
    `VAPID_SUBJECT=${vapidSubject}`,
    '',
    `SITE_URL=${siteUrl}`,
    '',
    `WEBHOOK_SECRET=${webhook}`,
    '',
  ]

  fs.writeFileSync(ENV_PATH, lines.join('\n'), 'utf8')
  console.log(`[write-env-local] OK → ${path.relative(ROOT, ENV_PATH)}`)
}

main()
